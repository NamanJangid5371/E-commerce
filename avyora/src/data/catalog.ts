export function getProduct(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function getProductById(id: string) {
  return products.find((p) => p.id === id);
}

export function relatedProducts(slug: string, limit = 4) {
  const current = getProduct(slug);
  if (!current) return products.slice(0, limit);
  return products
    .filter((p) => p.slug !== slug && (p.collection === current.collection || p.category === current.category))
    .slice(0, limit);
}

export function displayPrice(product: Product) {
  const prices = product.variants.map((v) => v.salePrice ?? v.price);
  const originals = product.variants.map((v) => v.price);
  return {
    from: Math.min(...prices),
    originalFrom: Math.min(...originals),
    onSale: product.variants.some((v) => v.salePrice && v.salePrice < v.price),
  };
}

export function variantStock(product: Product) {
  return product.variants.reduce((sum, v) => sum + v.stock, 0);
}
